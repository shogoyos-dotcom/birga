/// Niqobni ochadi: 1 — quruqlik, 0 — suv.
Uint8List decodeWorldLand() {
  final bytes = base64Decode(_packed);
  final land = Uint8List(kWorldWidth * kWorldHeight);
  for (var i = 0; i < land.length; i++) {
    land[i] = (bytes[i >> 3] >> (i & 7)) & 1;
  }
  return land;
}
